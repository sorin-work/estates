CREATE TABLE charges (
    id               uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    lease_id         uuid NOT NULL REFERENCES leases (id) ON DELETE CASCADE,
    kind             text NOT NULL,
    description      text NOT NULL DEFAULT '',
    amount_cents     bigint NOT NULL CHECK (amount_cents > 0),
    due_date         date NOT NULL,
    period_start     date,
    period_end       date,
    -- Late fees point at the rent charge they were added for.
    parent_charge_id uuid REFERENCES charges (id) ON DELETE CASCADE,
    created_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX charges_lease_id_due_date_idx ON charges (lease_id, due_date);
-- Rent is generated by a background job; this keeps it idempotent.
CREATE UNIQUE INDEX charges_one_rent_per_period ON charges (lease_id, due_date) WHERE kind = 'rent';
CREATE UNIQUE INDEX charges_one_late_fee_per_charge ON charges (parent_charge_id) WHERE kind = 'late_fee';

CREATE TABLE payments (
    id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    lease_id     uuid NOT NULL REFERENCES leases (id) ON DELETE CASCADE,
    amount_cents bigint NOT NULL CHECK (amount_cents > 0),
    paid_on      date NOT NULL,
    method       text NOT NULL DEFAULT 'bank_transfer',
    reference    text NOT NULL DEFAULT '',
    notes        text NOT NULL DEFAULT '',
    created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX payments_lease_id_idx ON payments (lease_id);

